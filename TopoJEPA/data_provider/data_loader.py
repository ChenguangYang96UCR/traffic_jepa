class Dataset_Custom(Dataset):
    def __init__(self, root_path, flag='train', size=None,
                 features='S', data_path='ETTh1.csv',
                 target='OT', scale=True, timeenc=0, freq='h',
                 text_embedding_dir=''):
        # size [seq_len, label_len, pred_len, future_len]
        # info
        if size == None:
            self.seq_len = 24 * 4 * 4
            self.label_len = 24 * 4
            self.pred_len = 24 * 4
        else:
            self.seq_len = size[0]
            self.label_len = size[1]
            self.pred_len = size[2]
        self.future_len = size[3] if size is not None and len(size) > 3 else self.pred_len
        # init
        assert flag in ['train', 'test', 'val']
        type_map = {'train': 0, 'val': 1, 'test': 2}
        self.set_type = type_map[flag]

        self.features = features
        self.target = target
        self.scale = scale
        self.timeenc = timeenc
        self.freq = freq
        self.flag = flag
        self.text_embedding_dir = text_embedding_dir

        self.root_path = root_path
        self.data_path = data_path
        self.__read_data__()

    def __read_data__(self):
        self.scaler = StandardScaler()
        df_raw = pd.read_csv(os.path.join(self.root_path,
                                          self.data_path))

        '''
        df_raw.columns: ['date', ...(other features), target feature]
        '''
        cols = list(df_raw.columns)
        cols.remove(self.target)
        cols.remove('date')
        df_raw = df_raw[['date'] + cols + [self.target]]
        num_train = int(len(df_raw) * 0.6)
        num_test = int(len(df_raw) * 0.2)
        num_vali = len(df_raw) - num_train - num_test

        value_cols = [col for col in df_raw.columns if col != 'date']
        df_raw[value_cols] = df_raw[value_cols].replace([np.inf, -np.inf], np.nan)
        df_raw[value_cols] = df_raw[value_cols].ffill()
        train_medians = df_raw.loc[:num_train - 1, value_cols].median(numeric_only=True)
        df_raw[value_cols] = df_raw[value_cols].fillna(train_medians).fillna(0.0)

        border1s = [0, num_train - self.seq_len, len(df_raw) - num_test - self.seq_len]
        border2s = [num_train, num_train + num_vali, len(df_raw)]
        border1 = border1s[self.set_type]
        border2 = border2s[self.set_type]

        if self.features == 'M' or self.features == 'MS':
            cols_data = df_raw.columns[1:]
            df_data = df_raw[cols_data]
        elif self.features == 'S':
            df_data = df_raw[[self.target]]

        if self.scale:
            train_data = df_data[border1s[0]:border2s[0]]
            self.scaler.fit(train_data.values)
            data = self.scaler.transform(df_data.values)
        else:
            data = df_data.values

        df_stamp = df_raw[['date']][border1:border2]
        df_stamp['date'] = pd.to_datetime(df_stamp.date)
        if self.timeenc == 0:
            df_stamp['month'] = df_stamp.date.apply(lambda row: row.month, 1)
            df_stamp['day'] = df_stamp.date.apply(lambda row: row.day, 1)
            df_stamp['weekday'] = df_stamp.date.apply(lambda row: row.weekday(), 1)
            df_stamp['hour'] = df_stamp.date.apply(lambda row: row.hour, 1)
            data_stamp = df_stamp.drop(['date'], 1).values
        elif self.timeenc == 1:
            data_stamp = time_features(pd.to_datetime(df_stamp['date'].values), freq=self.freq)
            data_stamp = data_stamp.transpose(1, 0)

        self.data_x = data[border1:border2]
        self.data_y = data[border1:border2]
        self.raw_y = df_data.values[border1:border2].astype(np.float32)
        self.feature_names = list(df_data.columns)
        self.data_stamp = data_stamp

        self.text_embeddings = None
        if self.text_embedding_dir:
            cache_file = clip_cache_path(
                self.text_embedding_dir, self.data_path, self.flag,
                self.seq_len, self.pred_len, self.future_len)
            if not os.path.exists(cache_file):
                raise FileNotFoundError(
                    f'Text embedding cache not found: {cache_file}. '
                    'Run scripts/text_jepa/precompute_clip_embeddings.py first.')
            self.text_embeddings = np.load(cache_file, mmap_mode='r')
            expected = (len(self), len(self.feature_names), 512)
            if self.text_embeddings.shape != expected:
                raise ValueError(
                    f'Invalid text embedding cache shape {self.text_embeddings.shape}; '
                    f'expected {expected}: {cache_file}')

    def __getitem__(self, index):
        s_begin = index
        s_end = s_begin + self.seq_len
        r_begin = s_end - self.label_len
        r_end = r_begin + self.label_len + self.future_len

        seq_x = self.data_x[s_begin:s_end]
        seq_y = self.data_y[r_begin:r_end]
        seq_x_mark = self.data_stamp[s_begin:s_end]
        seq_y_mark = self.data_stamp[r_begin:r_end]

        if self.text_embeddings is not None:
            text_target = np.array(self.text_embeddings[index], dtype=np.float32)
            return seq_x, seq_y, seq_x_mark, seq_y_mark, text_target
        return seq_x, seq_y, seq_x_mark, seq_y_mark

    def __len__(self):
        return len(self.data_x) - self.seq_len - self.future_len + 1

    def inverse_transform(self, data):
        return self.scaler.inverse_transform(data)


